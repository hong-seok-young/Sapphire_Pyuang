// 새 메뉴를 만들거나 단추를 바꾸면 여기도 같이 고친다. 단추 이름은 화면 글자 그대로 쓴다.
import type { Me } from "./auth";
import { RANK, TEST_IDS } from "./auth";

/** 누구에게 보이는 글인지: all 모두 | main 1군 | officer 오피서 이상 | master 길드마스터·앱개발자 | developer 앱개발자 | rentStaff 장비대여 운영(길드마스터·대여 담당·앱개발자) */
export type Who = "all" | "main" | "officer" | "master" | "developer" | "rentStaff";

export interface GuideButton {
  name: string;
  what: string;
  who?: Who;
}
export interface GuideFlow {
  /** 흐름 제목 (예: '물건 팔기') */
  title: string;
  steps: string[];
  who?: Who;
}
export interface GuideStep {
  /** 비출 곳 (CSS 선택자, 없으면 화면 전체 설명). 여러 개면 처음 보이는 것 */
  sel?: string;
  text: string;
  /** true 면 '눌러 보세요': 그 곳을 누르면 다음으로. 아니면 '다음' 단추 */
  tap?: boolean;
  /** 이 단계 전에 이동할 주소 (칸 바꾸기 등) */
  go?: string;
  who?: Who;
}
export interface Guide {
  /** 화면 주소 첫 칸 (ranking, market …) */
  key: string;
  title: string;
  /** 한 줄 (무엇을 하는 메뉴인지) */
  intro: string;
  buttons: GuideButton[];
  flows: GuideFlow[];
  tutorial: GuideStep[];
}

/** 대여 담당 (server/rental.ts RENT_STAFF 와 같다) */
const RENT_STAFF = ["멍멍"];

/** 그 글이 이 사람에게 보이는지 */
export function canSee(who: Who | undefined, me: Me): boolean {
  switch (who) {
    case undefined:
    case "all":
      return true;
    case "main":
      return me.guild === "main" || me.role === "developer";
    case "officer":
      return RANK[me.role] >= 1;
    case "master":
      return RANK[me.role] >= 2;
    case "developer":
      return me.role === "developer" || TEST_IDS.includes(me.id);
    case "rentStaff":
      return me.role === "master" || me.role === "developer" || RENT_STAFF.includes(me.id) || (me.characters ?? []).some((c) => RENT_STAFF.includes(c.id));
  }
}

