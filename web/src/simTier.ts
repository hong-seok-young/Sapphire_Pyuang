/** 재질 하나의 칭호 수와, 가운데 그림 하나를 같이 쓰는 칭호 수 */
export const ERA_TITLES = 24;
export const FAM_TITLES = 4;
/** 칭호 하나의 계급 수 */
export const GRADES = 5;
/** 이름이 있는 계급 수 (그 뒤는 끝없이) */
export const NAMED = TIER_TITLES.length * GRADES;
const BEYOND = "이름 없는 신";
export const ERA_NAMES = ["나무", "무쇠", "청동", "은", "금", "에메랄드", "사파이어", "루비", "자수정", "오팔", "우주", "태초"];

/** 계급 n 이 되는 명성 */
export const tierXp = (n: number) => Math.round(10 * Math.pow(Math.max(0, n) / 4, 2.15));
/** 명성으로 계급 번호 (0 부터) */
export function rankOf(xp: number): number {
  let n = Math.max(0, Math.floor(4 * Math.pow(Math.max(0, xp) / 10, 1 / 2.15)));
  while (tierXp(n + 1) <= xp) n++;
  while (n > 0 && tierXp(n) > xp) n--;
  return n;
}

export interface Tier {
  /** 계급 번호 (0 부터, 끝없이) */
  n: number;
  /** 재질 0 ~ 11 (11 = 이름 있는 계급을 다 넘은 뒤) */
  era: number;
  /** 가운데 그림 0 ~ 5 (동전 · 망치 · 클로버 · 보석 · 별 · 왕관) */
  fam: number;
  /** 같은 그림 안에서 몇째 칭호인가 0 ~ 3 (계급장 오른쪽 작은 줄) */
  sub: number;
  /** 칭호 안의 계급 1 ~ 5 (아래 다섯 칸) */
  grade: number;
  title: string;
  /** 칭호와 계급: '금손 3' */
  name: string;
  /** 이 계급이 시작하는 명성과 다음 계급이 되는 명성 */
  from: number;
  next: number;
}
export function tierAt(n: number): Tier {
  const k = Math.max(0, Math.floor(n));
  if (k >= NAMED) {
    const over = k - NAMED + 1;
    return { n: k, era: 11, fam: 5, sub: FAM_TITLES - 1, grade: GRADES, title: BEYOND, name: `${BEYOND} ${over.toLocaleString()}`, from: tierXp(k), next: tierXp(k + 1) };
  }
  const t = Math.floor(k / GRADES);
  const grade = (k % GRADES) + 1;
  const inEra = t % ERA_TITLES;
  return { n: k, era: Math.floor(t / ERA_TITLES), fam: Math.floor(inEra / FAM_TITLES), sub: inEra % FAM_TITLES, grade, title: TIER_TITLES[t], name: `${TIER_TITLES[t]} ${grade}`, from: tierXp(k), next: tierXp(k + 1) };
}
export const tierOfXp = (xp: number) => tierAt(rankOf(xp));
/** 다음 계급까지 얼마나 왔나 (0 ~ 1) */
export const tierProgress = (xp: number, t: Tier = tierOfXp(xp)) => Math.min(1, Math.max(0, (xp - t.from) / Math.max(1, t.next - t.from)));
/** 새 칭호가 됐나 (다섯 계급마다, 화면에서 크게 축하) */
export const isNewTitle = (n: number) => n > 0 && n % GRADES === 0;
/** 전광판에 알리는 마디: 가운데 그림이 바뀔 때 (칭호 넷 = 계급 스물마다. 칭호마다 알리면 전광판이 승급으로 찬다) */
export const FEED_EVERY = GRADES * FAM_TITLES;
